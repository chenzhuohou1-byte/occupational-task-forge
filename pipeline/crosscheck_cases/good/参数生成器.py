"""按 规则.md 采样「世界参数」：边界世界前置，再 seeded 随机补满。

边界清单（同事要求的具体档）：跨档分界(单价==封顶) / 封顶触发(单价>封顶) / 保底(单价<封顶)
/ 城市未备案 / 零天数 / 空明细 / 单行 / 最大规模 / 负数单价 / 重复行键。
封顶取非 10 整数(503/517/349)、随机单价取 10 的倍数 → 随机永不等于封顶，
故"单价==封顶"这个切换点只在边界世界出现（演示：不采边界会漏掉只在该点暴露的 bug）。
"""
import random

STD = {"北京": 503, "上海": 517, "成都": 349}
CITIES = list(STD)


def _w(明细):
    return {"城市标准": dict(STD), "明细": 明细}


BOUNDARY = [
    _w([{"行号": 1, "城市": "北京", "住宿单价": 503, "天数": 2}]),   # 跨档分界：单价==封顶
    _w([{"行号": 1, "城市": "上海", "住宿单价": 800, "天数": 1}]),   # 封顶触发：单价>封顶
    _w([{"行号": 1, "城市": "成都", "住宿单价": 200, "天数": 3}]),   # 保底：单价<封顶
    _w([{"行号": 1, "城市": "广州", "住宿单价": 400, "天数": 2}]),   # 城市未备案
    _w([{"行号": 1, "城市": "北京", "住宿单价": 600, "天数": 0}]),   # 零天数
    _w([]),                                                          # 空明细
    _w([{"行号": 1, "城市": "北京", "住宿单价": -50, "天数": 2}]),   # 负数单价（录入错误）
    _w([{"行号": 1, "城市": "北京", "住宿单价": 400, "天数": 1},
        {"行号": 1, "城市": "上海", "住宿单价": 400, "天数": 1}]),   # 重复行键
    _w([{"行号": i + 1, "城市": CITIES[i % 3], "住宿单价": 100 + 10 * i, "天数": 1 + i % 5}
        for i in range(60)]),                                       # 最大规模
]


def worlds(n, seed=0, boundary=True):
    out = [dict(w) for w in BOUNDARY] if boundary else []
    rng = random.Random(seed)
    while len(out) < n:
        rows = rng.randint(1, 6)
        明细 = [{"行号": i + 1, "城市": rng.choice(CITIES + ["未备案城市"]),
                "住宿单价": rng.randrange(100, 1000, 10), "天数": rng.randint(0, 10)}
               for i in range(rows)]
        out.append(_w(明细))
    return out[:n]
